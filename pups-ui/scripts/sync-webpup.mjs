#!/usr/bin/env node
// Builds webpup (next to pups-ui in the PUPS repository) and writes its build into src/webpup-files.ts,
// from where the TypeScript servers serve it when the owner installs it as the homepage (/pups/homepage).
// The servers are bundled, so the build travels as a module: text files as strings, images as base64.
import { execSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const webpup = join(root, '../webpup')
if (!existsSync(join(webpup, 'package.json'))) throw new Error('webpup not found next to pups-ui')
if (!process.argv.includes('--no-build')) execSync('npm run build --silent', { cwd: webpup, stdio: 'inherit' })
const dist = join(webpup, 'dist')
const types = { html: 'text/html', js: 'text/javascript', css: 'text/css', json: 'application/json', jpg: 'image/jpeg' }
const files = {}
const walk = dir => {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) walk(path)
    else {
      const ext = name.split('.').pop()
      if (!types[ext]) throw new Error(`Unknown file type: ${path}`)
      const key = '/' + relative(dist, path)
      files[key] = ext == 'jpg' ? { type: types[ext], base64: readFileSync(path).toString('base64') } : { type: types[ext], text: readFileSync(path, 'utf8') }
    }
  }
}
walk(dist)
writeFileSync(join(root, 'src/webpup-files.ts'), `// Generated by scripts/sync-webpup.mjs from webpup's build. Don't edit; run the script.
export const WEBPUP_FILES: Record<string, { type: string; text?: string; base64?: string }> = ${JSON.stringify(files, null, 1)}
`)
console.log(`Wrote ${Object.keys(files).length} files of webpup into src/webpup-files.ts.`)
